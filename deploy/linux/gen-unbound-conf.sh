#!/bin/sh
# Generate Unbound conf sized from host RAM/CPU so upgrades apply on next recreate.
# Usage:
#   deploy/linux/gen-unbound-conf.sh [outfile]
# Unbound is the recursive backend behind dnsdist on 127.0.0.1:5353; it never answers
# clients directly (ADR-0001). The only mode is the dnsdist backend.
set -eu

ROOT="$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)"
OUT="${1:-$ROOT/configs/unbound/unbound.conf}"

case "${POWERSVX_UNBOUND_MODE:-backend}" in
  backend|dnsdist-backend) ;;
  *) echo "POWERSVX_UNBOUND_MODE=${POWERSVX_UNBOUND_MODE} is not supported: the Unbound-on-the-public-port mode was removed; Unbound only runs as the backend behind dnsdist." >&2; exit 1 ;;
esac
case "${POWERSVX_DNS_DATAPLANE:-}" in
  unbound|external) echo "POWERSVX_DNS_DATAPLANE=${POWERSVX_DNS_DATAPLANE} is not supported: the Unbound-on-the-public-port mode was removed; use dnsdist (docs/PRODUCTION.md)." >&2; exit 1 ;;
esac
MODE=dnsdist-backend

# POWERSVX_HOST_CPUS / POWERSVX_HOST_MEM_MB size the config for a smaller node than
# the machine it is generated on (benchmarks at a fixed size).
case "${POWERSVX_HOST_MEM_MB:-}" in
  '') MEM_KB=$(awk '/MemTotal:/ {print $2}' /proc/meminfo) ;;
  *[!0-9]*) echo "POWERSVX_HOST_MEM_MB must be a whole number of MB" >&2; exit 1 ;;
  *) MEM_KB=$((POWERSVX_HOST_MEM_MB * 1024)) ;;
esac
case "${POWERSVX_HOST_CPUS:-}" in
  '') NPROC=$(nproc 2>/dev/null || echo 4) ;;
  *[!0-9]*|0) echo "POWERSVX_HOST_CPUS must be a positive whole number" >&2; exit 1 ;;
  *) NPROC=$POWERSVX_HOST_CPUS ;;
esac
case $NPROC in
  ''|*[!0-9]*) NPROC=4 ;;
esac
if [ -z "$MEM_KB" ] || [ "$MEM_KB" -lt 65536 ]; then
  MEM_KB=2097152
fi
MEM_MB=$((MEM_KB / 1024))

THREADS=$((NPROC / 2))
if [ "$THREADS" -lt 2 ]; then THREADS=2; fi
if [ "$THREADS" -gt 16 ]; then THREADS=16; fi
# Tuning knobs (ticket #18). Both are off by default, which keeps today's configuration.
# POWERSVX_UNBOUND_THREADS: half (default: half the CPUs, 2 to 16), all (every CPU, 2 to 32),
# or a whole number from 1 to 32.
case "${POWERSVX_UNBOUND_THREADS:-half}" in
  half) ;;
  all) THREADS=$NPROC
       if [ "$THREADS" -lt 2 ]; then THREADS=2; fi
       if [ "$THREADS" -gt 32 ]; then THREADS=32; fi ;;
  *[!0-9]*|0|0?*) echo "POWERSVX_UNBOUND_THREADS must be half, all or a whole number from 1 to 32" >&2; exit 1 ;;
  *) if [ "$POWERSVX_UNBOUND_THREADS" -gt 32 ]; then echo "POWERSVX_UNBOUND_THREADS must be half, all or a whole number from 1 to 32" >&2; exit 1; fi
     THREADS=$POWERSVX_UNBOUND_THREADS ;;
esac
# POWERSVX_UNBOUND_PREFETCH: no (default) or yes.
PREFETCH="${POWERSVX_UNBOUND_PREFETCH:-no}"
case "$PREFETCH" in
  yes|no) ;;
  *) echo "POWERSVX_UNBOUND_PREFETCH must be yes or no" >&2; exit 1 ;;
esac

MSG_MB=$((MEM_MB * 2 / 100))
RRSET_MB=$((MEM_MB * 4 / 100))
if [ "$MSG_MB" -lt 64 ]; then MSG_MB=64; fi
if [ "$MSG_MB" -gt 2048 ]; then MSG_MB=2048; fi
if [ "$RRSET_MB" -lt 128 ]; then RRSET_MB=128; fi
if [ "$RRSET_MB" -gt 4096 ]; then RRSET_MB=4096; fi
KEY_MB=$((MSG_MB / 4))
if [ "$KEY_MB" -lt 16 ]; then KEY_MB=16; fi
if [ "$KEY_MB" -gt 256 ]; then KEY_MB=256; fi
NEG_MB=$((MSG_MB / 8))
if [ "$NEG_MB" -lt 8 ]; then NEG_MB=8; fi
if [ "$NEG_MB" -gt 128 ]; then NEG_MB=128; fi

  OUTGOING=$((THREADS * 1024))
  if [ "$OUTGOING" -lt 2048 ]; then OUTGOING=2048; fi
  if [ "$OUTGOING" -gt 8192 ]; then OUTGOING=8192; fi
  QPT=$((THREADS * 512))
  if [ "$QPT" -lt 1024 ]; then QPT=1024; fi
  if [ "$QPT" -gt 4096 ]; then QPT=4096; fi

# Unbound requires cache slab counts to be powers of two (threads may be any integer).
SLABS=1
while [ "$SLABS" -lt "$THREADS" ]; do
  SLABS=$((SLABS * 2))
done

RPZ_DIR_HOST="$ROOT/data/unbound-rpz"
LOG_DIR_HOST="$ROOT/data/unbound-logs"
mkdir -p "$RPZ_DIR_HOST" "$LOG_DIR_HOST"
chmod 777 "$LOG_DIR_HOST" 2>/dev/null || true
# Drop-ins the Control Plane rewrites at runtime; present and empty so Unbound starts first.
if [ ! -f "$RPZ_DIR_HOST/runtime-server.conf" ]; then
  cat >"$RPZ_DIR_HOST/runtime-server.conf" <<'Z'
# PowerSVX dynamic server-scope options (populated on startup & settings save)
    do-not-query-localhost: no
Z
fi
if [ ! -f "$RPZ_DIR_HOST/runtime-zones.conf" ]; then
  cat >"$RPZ_DIR_HOST/runtime-zones.conf" <<'Z'
# PowerSVX dynamic forward-zone & stub-zone clauses (populated on startup & settings save)
Z
fi

TMP="${OUT}.tmp.$$"

cat >"$TMP" <<EOF
# PowerSVX hybrid backend: Unbound recursive on loopback only.
# AUTO-GENERATED by deploy/linux/gen-unbound-conf.sh - mode=${MODE}
# host MemTotal=${MEM_MB}MB nproc=${NPROC} -> threads=${THREADS} msg=${MSG_MB}m rrset=${RRSET_MB}m

server:
    verbosity: 1
    username: "_unbound"
    directory: "/opt/unbound/etc/unbound"
    do-daemonize: no

    interface: 127.0.0.1
    port: 5353
    do-ip4: yes
    do-ip6: yes
    do-udp: yes
    do-tcp: yes
    prefer-ip6: no
    so-reuseport: yes

    access-control: 127.0.0.1/32 allow
    access-control: ::1/128 allow
    access-control: 0.0.0.0/0 refuse
    access-control: ::/0 refuse

    hide-identity: yes
    hide-version: yes
    harden-glue: yes
    harden-dnssec-stripped: yes
    use-caps-for-id: no
    qname-minimisation: no
    infra-keep-probing: no
    aggressive-nsec: yes
    prefetch: ${PREFETCH}
    prefetch-key: yes
    domain-insecure: "in-addr.arpa."
    domain-insecure: "ip6.arpa."
    serve-expired: yes
    serve-expired-ttl: 86400
    edns-buffer-size: 1232

    num-threads: ${THREADS}
    msg-cache-slabs: ${SLABS}
    rrset-cache-slabs: ${SLABS}
    infra-cache-slabs: ${SLABS}
    key-cache-slabs: ${SLABS}
    msg-cache-size: ${MSG_MB}m
    rrset-cache-size: ${RRSET_MB}m
    key-cache-size: ${KEY_MB}m
    neg-cache-size: ${NEG_MB}m
    outgoing-range: ${OUTGOING}
    num-queries-per-thread: ${QPT}
    jostle-timeout: 200
    unwanted-reply-threshold: 10000

    auto-trust-anchor-file: "/opt/unbound/etc/unbound/var/root.key"

    include: /opt/unbound/etc/unbound/a-records.conf
    include: /opt/unbound/etc/unbound/srv-records.conf
    include: /opt/unbound/etc/unbound/rpz/runtime-server.conf

include: /opt/unbound/etc/unbound/rpz/runtime-zones.conf

remote-control:
    control-enable: yes
    control-interface: 127.0.0.1
    control-port: 8953
    control-use-cert: no
EOF

mv -f "$TMP" "$OUT"
echo "unbound-conf: wrote $OUT mode=${MODE} (threads=${THREADS} msg=${MSG_MB}m rrset=${RRSET_MB}m outgoing=${OUTGOING} qpt=${QPT} prefetch=${PREFETCH})" >&2
