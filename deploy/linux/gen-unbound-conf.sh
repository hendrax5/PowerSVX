#!/bin/sh
# Generate Unbound conf sized from host RAM/CPU so upgrades apply on next recreate.
# Usage:
#   deploy/linux/gen-unbound-conf.sh [outfile]
# Env:
#   POWERSVX_UNBOUND_MODE=dataplane|backend
#     dataplane — public :53 (PowerSVX is API-only)
#     backend   — 127.0.0.1:5353 only (legacy hybrid; default if unset and not dataplane)
#   POWERSVX_DNS_DATAPLANE=unbound → forces dataplane mode
set -eu

ROOT="$(CDPATH= cd -- "$(dirname "$0")/../.." && pwd)"
OUT="${1:-$ROOT/configs/unbound/unbound.conf}"

MODE="${POWERSVX_UNBOUND_MODE:-}"
if [ -z "$MODE" ]; then
  case "${POWERSVX_DNS_DATAPLANE:-}" in
    unbound|external) MODE=dataplane ;;
    dnsdist|cdb) MODE=dnsdist-backend ;;
    *) MODE=backend ;;
  esac
fi

MEM_KB=$(awk '/MemTotal:/ {print $2}' /proc/meminfo)
NPROC=$(nproc 2>/dev/null || echo 4)
case $NPROC in
  ''|*[!0-9]*) NPROC=4 ;;
esac
if [ -z "$MEM_KB" ] || [ "$MEM_KB" -lt 65536 ]; then
  MEM_KB=2097152
fi
MEM_MB=$((MEM_KB / 1024))

THREADS=$((NPROC / 2))
if [ "$THREADS" -lt 2 ]; then THREADS=2; fi
if [ "$THREADS" -gt 16 ]; then THREADS=16; fi

MSG_MB=$((MEM_MB * 2 / 100))
RRSET_MB=$((MEM_MB * 4 / 100))
if [ "$MSG_MB" -lt 64 ]; then MSG_MB=64; fi
if [ "$MSG_MB" -gt 2048 ]; then MSG_MB=2048; fi
if [ "$RRSET_MB" -lt 128 ]; then RRSET_MB=128; fi
if [ "$RRSET_MB" -gt 4096 ]; then RRSET_MB=4096; fi
KEY_MB=$((MSG_MB / 4))
if [ "$KEY_MB" -lt 16 ]; then KEY_MB=16; fi
if [ "$KEY_MB" -gt 256 ]; then KEY_MB=256; fi
NEG_MB=$((MSG_MB / 8))
if [ "$NEG_MB" -lt 8 ]; then NEG_MB=8; fi
if [ "$NEG_MB" -gt 128 ]; then NEG_MB=128; fi

if [ "$MODE" = "dataplane" ]; then
  # TrustPositif RPZ (~9.5M) dominates RAM; keep recurse caches/threads small.
  if [ "$THREADS" -gt 4 ]; then THREADS=4; fi
  MSG_MB=32
  RRSET_MB=64
  KEY_MB=16
  NEG_MB=8
  OUTGOING=$((THREADS * 512))
  if [ "$OUTGOING" -lt 2048 ]; then OUTGOING=2048; fi
  if [ "$OUTGOING" -gt 4096 ]; then OUTGOING=4096; fi
  QPT=$((THREADS * 256))
  if [ "$QPT" -lt 1024 ]; then QPT=1024; fi
  if [ "$QPT" -gt 2048 ]; then QPT=2048; fi
else
  OUTGOING=$((THREADS * 1024))
  if [ "$OUTGOING" -lt 2048 ]; then OUTGOING=2048; fi
  if [ "$OUTGOING" -gt 8192 ]; then OUTGOING=8192; fi
  QPT=$((THREADS * 512))
  if [ "$QPT" -lt 1024 ]; then QPT=1024; fi
  if [ "$QPT" -gt 4096 ]; then QPT=4096; fi
fi

# Unbound requires cache slab counts to be powers of two (threads may be any integer).
SLABS=1
while [ "$SLABS" -lt "$THREADS" ]; do
  SLABS=$((SLABS * 2))
done

RPZ_DIR_HOST="$ROOT/data/unbound-rpz"
LOG_DIR_HOST="$ROOT/data/unbound-logs"
mkdir -p "$RPZ_DIR_HOST" "$LOG_DIR_HOST"
chmod 777 "$LOG_DIR_HOST" 2>/dev/null || true
# Minimal zones so Unbound starts before PowerSVX sync.
# Owners must be under the RPZ apex ($ORIGIN); absolute client names break unbound-checkconf.
if [ ! -f "$RPZ_DIR_HOST/banks.rpz" ]; then
  cat >"$RPZ_DIR_HOST/banks.rpz" <<'Z'
$TTL 60
$ORIGIN rpz.banks.
@ SOA localhost. root.localhost. 1 3600 600 86400 60
@ NS localhost.
Z
fi
if [ ! -f "$RPZ_DIR_HOST/trustpositif.rpz" ]; then
  cat >"$RPZ_DIR_HOST/trustpositif.rpz" <<'Z'
$TTL 60
$ORIGIN rpz.trustpositif.
@ SOA localhost. root.localhost. 1 3600 600 86400 60
@ NS localhost.
Z
fi
if [ ! -f "$RPZ_DIR_HOST/axfr.rpz" ]; then
  cat >"$RPZ_DIR_HOST/axfr.rpz" <<'Z'
$TTL 60
$ORIGIN rpz.axfr.
@ SOA localhost. root.localhost. 1 3600 600 86400 60
@ NS localhost.
Z
fi
if [ ! -f "$RPZ_DIR_HOST/access-control.conf" ]; then
  cat >"$RPZ_DIR_HOST/access-control.conf" <<'Z'
# Default open until PowerSVX writes allow_query CIDRs.
access-control: 127.0.0.1/32 allow
access-control: ::1/128 allow
access-control: 0.0.0.0/0 allow
access-control: ::/0 allow
Z
fi
if [ ! -f "$RPZ_DIR_HOST/runtime-server.conf" ]; then
  cat >"$RPZ_DIR_HOST/runtime-server.conf" <<'Z'
# PowerSVX dynamic server-scope options (populated on startup & settings save)
    do-not-query-localhost: no
Z
fi
if [ ! -f "$RPZ_DIR_HOST/runtime-zones.conf" ]; then
  cat >"$RPZ_DIR_HOST/runtime-zones.conf" <<'Z'
# PowerSVX dynamic forward-zone & stub-zone clauses (populated on startup & settings save)
Z
fi

TMP="${OUT}.tmp.$$"

if [ "$MODE" = "dataplane" ]; then
cat >"$TMP" <<EOF
# PowerSVX dataplane: Unbound owns public DNS :53. PowerSVX is API/control-plane only.
# AUTO-GENERATED by deploy/linux/gen-unbound-conf.sh - mode=${MODE}
# host MemTotal=${MEM_MB}MB nproc=${NPROC} -> threads=${THREADS} msg=${MSG_MB}m rrset=${RRSET_MB}m

server:
    verbosity: 1
    username: "_unbound"
    directory: "/opt/unbound/etc/unbound"
    do-daemonize: no

    interface: 0.0.0.0
    port: 53
    do-ip4: yes
    do-ip6: yes
    do-udp: yes
    do-tcp: yes
    prefer-ip6: no
    so-reuseport: yes

    include: /opt/unbound/etc/unbound/rpz/access-control.conf

    hide-identity: yes
    hide-version: yes
    harden-glue: yes
    harden-dnssec-stripped: yes
    use-caps-for-id: no
    qname-minimisation: no
    infra-keep-probing: no
    aggressive-nsec: yes
    prefetch: no
    prefetch-key: yes
    domain-insecure: "in-addr.arpa."
    domain-insecure: "ip6.arpa."
    serve-expired: yes
    serve-expired-ttl: 86400
    edns-buffer-size: 1232
    module-config: "respip validator iterator"
    extended-statistics: yes
    statistics-cumulative: yes
    statistics-interval: 0

    num-threads: ${THREADS}
    msg-cache-slabs: ${SLABS}
    rrset-cache-slabs: ${SLABS}
    infra-cache-slabs: ${SLABS}
    key-cache-slabs: ${SLABS}
    msg-cache-size: ${MSG_MB}m
    rrset-cache-size: ${RRSET_MB}m
    key-cache-size: ${KEY_MB}m
    neg-cache-size: ${NEG_MB}m
    outgoing-range: ${OUTGOING}
    num-queries-per-thread: ${QPT}
    jostle-timeout: 200
    unwanted-reply-threshold: 10000

    auto-trust-anchor-file: "/opt/unbound/etc/unbound/var/root.key"

    include: /opt/unbound/etc/unbound/a-records.conf
    include: /opt/unbound/etc/unbound/srv-records.conf
    include: /opt/unbound/etc/unbound/rpz/runtime-server.conf

    # Query logfile optional — full log-queries under multi-k QPS + 9.5M RPZ can stall Unbound.
    # Keep file path for future sampling; default queries logging OFF for stability.
    use-syslog: no
    logfile: "/opt/unbound/etc/unbound/logs/unbound.log"
    log-time-ascii: yes
    log-queries: no
    log-replies: no
    log-servfail: no

include: /opt/unbound/etc/unbound/rpz/runtime-zones.conf

# Bank passthru first, then AXFR feeds, then TrustPositif hosts (~9.5M).
rpz:
    name: "rpz.banks."
    zonefile: "/opt/unbound/etc/unbound/rpz/banks.rpz"
    rpz-log: yes
    rpz-log-name: banks

rpz:
    name: "rpz.axfr."
    zonefile: "/opt/unbound/etc/unbound/rpz/axfr.rpz"
    rpz-log: yes
    rpz-log-name: axfr

rpz:
    name: "rpz.trustpositif."
    zonefile: "/opt/unbound/etc/unbound/rpz/trustpositif.rpz"
    rpz-log: yes
    rpz-log-name: trustpositif

remote-control:
    control-enable: yes
    control-interface: 127.0.0.1
    control-port: 8953
    control-use-cert: no
EOF
else
cat >"$TMP" <<EOF
# PowerSVX hybrid backend: Unbound recursive on loopback only.
# AUTO-GENERATED by deploy/linux/gen-unbound-conf.sh - mode=${MODE}
# host MemTotal=${MEM_MB}MB nproc=${NPROC} -> threads=${THREADS} msg=${MSG_MB}m rrset=${RRSET_MB}m

server:
    verbosity: 1
    username: "_unbound"
    directory: "/opt/unbound/etc/unbound"
    do-daemonize: no

    interface: 127.0.0.1
    port: 5353
    do-ip4: yes
    do-ip6: yes
    do-udp: yes
    do-tcp: yes
    prefer-ip6: no
    so-reuseport: yes

    access-control: 127.0.0.1/32 allow
    access-control: ::1/128 allow
    access-control: 0.0.0.0/0 refuse
    access-control: ::/0 refuse

    hide-identity: yes
    hide-version: yes
    harden-glue: yes
    harden-dnssec-stripped: yes
    use-caps-for-id: no
    qname-minimisation: no
    infra-keep-probing: no
    aggressive-nsec: yes
    prefetch: no
    prefetch-key: yes
    domain-insecure: "in-addr.arpa."
    domain-insecure: "ip6.arpa."
    serve-expired: yes
    serve-expired-ttl: 86400
    edns-buffer-size: 1232

    num-threads: ${THREADS}
    msg-cache-slabs: ${SLABS}
    rrset-cache-slabs: ${SLABS}
    infra-cache-slabs: ${SLABS}
    key-cache-slabs: ${SLABS}
    msg-cache-size: ${MSG_MB}m
    rrset-cache-size: ${RRSET_MB}m
    key-cache-size: ${KEY_MB}m
    neg-cache-size: ${NEG_MB}m
    outgoing-range: ${OUTGOING}
    num-queries-per-thread: ${QPT}
    jostle-timeout: 200
    unwanted-reply-threshold: 10000

    auto-trust-anchor-file: "/opt/unbound/etc/unbound/var/root.key"

    include: /opt/unbound/etc/unbound/a-records.conf
    include: /opt/unbound/etc/unbound/srv-records.conf
    include: /opt/unbound/etc/unbound/rpz/runtime-server.conf

include: /opt/unbound/etc/unbound/rpz/runtime-zones.conf

remote-control:
    control-enable: yes
    control-interface: 127.0.0.1
    control-port: 8953
    control-use-cert: no
EOF
fi

mv -f "$TMP" "$OUT"
echo "unbound-conf: wrote $OUT mode=${MODE} (threads=${THREADS} msg=${MSG_MB}m rrset=${RRSET_MB}m outgoing=${OUTGOING} qpt=${QPT})" >&2
