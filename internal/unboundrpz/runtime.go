package unboundrpz

import (
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/powersvx/powersvx/internal/config"
)

const (
	RuntimeServerFile = "runtime-server.conf"
	RuntimeZonesFile  = "runtime-zones.conf"
)

// RuntimeSyncSpec captures PowerSVX control-plane settings mirrored into Unbound drop-in configs.
type RuntimeSyncSpec struct {
	ResolverMode  string
	ForwardOnFail bool
	Forwarders    []string
	ForwardZones  []config.ForwardZoneConfig
	DNSSECMode    string
	ECSEnabled    bool
	AuthZones     []string
	AuthAddr      string // default 127.0.0.1@5354
}

// WriteRuntimeConfig renders runtime-server.conf (included inside Unbound's server: block)
// and runtime-zones.conf (stub-zone for local auth zones + forward-zone directives).
func WriteRuntimeConfig(dataDir string, spec RuntimeSyncSpec) error {
	dir := Dir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	authAddr := strings.TrimSpace(spec.AuthAddr)
	if authAddr == "" {
		authAddr = "127.0.0.1@5354"
	}

	// Clean & sort authoritative zone names safely.
	seenZone := map[string]struct{}{}
	var authZones []string
	for _, z := range spec.AuthZones {
		nz := sanitizeUnboundDomain(z)
		if nz == "" {
			continue
		}
		if _, ok := seenZone[nz]; !ok {
			seenZone[nz] = struct{}{}
			authZones = append(authZones, nz)
		}
	}
	sort.Strings(authZones)

	// 1. Render server:-scoped runtime options
	var srv strings.Builder
	srv.WriteString("# AUTO-GENERATED by PowerSVX Control Plane - included in server:\n")
	if strings.EqualFold(strings.TrimSpace(spec.DNSSECMode), "off") {
		srv.WriteString("    val-permissive-mode: yes\n")
	} else {
		srv.WriteString("    val-permissive-mode: no\n")
	}
	if spec.ECSEnabled {
		srv.WriteString("    send-client-subnet: 0.0.0.0/0\n")
		srv.WriteString("    send-client-subnet: ::/0\n")
	}
	// Exempt local PowerSVX authoritative zones from upstream DNSSEC chain failures and localhost stub loop blocking.
	srv.WriteString("    do-not-query-localhost: no\n")
	for _, z := range authZones {
		fmt.Fprintf(&srv, "    private-domain: %q\n", z+".")
		fmt.Fprintf(&srv, "    domain-insecure: %q\n", z+".")
	}

	// 2. Render top-level stub-zone and forward-zone clauses
	var zones strings.Builder
	zones.WriteString("# AUTO-GENERATED by PowerSVX Control Plane - top-level zones\n")

	for _, z := range authZones {
		fmt.Fprintf(&zones, "stub-zone:\n")
		fmt.Fprintf(&zones, "    name: %q\n", z+".")
		fmt.Fprintf(&zones, "    stub-addr: %s\n", authAddr)
		fmt.Fprintf(&zones, "    stub-prime: no\n")
		fmt.Fprintf(&zones, "    stub-no-cache: yes\n\n")
	}

	for _, fz := range spec.ForwardZones {
		dom := sanitizeUnboundDomain(fz.Zone)
		if dom == "" {
			continue
		}
		addrs := sanitizeUnboundAddrs(fz.Forwarders)
		if len(addrs) == 0 {
			continue
		}
		fmt.Fprintf(&zones, "forward-zone:\n")
		fmt.Fprintf(&zones, "    name: %q\n", dom+".")
		for _, a := range addrs {
			fmt.Fprintf(&zones, "    forward-addr: %s\n", a)
		}
		if spec.ForwardOnFail {
			zones.WriteString("    forward-first: yes\n")
		}
		zones.WriteByte('\n')
	}

	if strings.EqualFold(strings.TrimSpace(spec.ResolverMode), "forward") {
		addrs := sanitizeUnboundAddrs(spec.Forwarders)
		if len(addrs) > 0 {
			zones.WriteString("forward-zone:\n")
			zones.WriteString("    name: \".\"\n")
			for _, a := range addrs {
				fmt.Fprintf(&zones, "    forward-addr: %s\n", a)
			}
			if spec.ForwardOnFail {
				zones.WriteString("    forward-first: yes\n")
			}
			zones.WriteByte('\n')
		}
	}

	if err := atomicWriteFile(filepath.Join(dir, RuntimeServerFile), []byte(srv.String())); err != nil {
		return err
	}
	return atomicWriteFile(filepath.Join(dir, RuntimeZonesFile), []byte(zones.String()))
}

func atomicWriteFile(path string, data []byte) error {
	if cur, err := os.ReadFile(path); err == nil && string(cur) == string(data) {
		return nil
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func sanitizeUnboundDomain(s string) string {
	s = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(s), "."))
	if s == "" || s == "." {
		return ""
	}
	for _, r := range s {
		if !((r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' || r == '.' || r == '_') {
			return ""
		}
	}
	return s
}

func sanitizeUnboundAddrs(in []string) []string {
	var out []string
	seen := map[string]struct{}{}
	for _, raw := range in {
		s := strings.TrimSpace(raw)
		if s == "" {
			continue
		}
		// Accept ip, ip:port, or Unbound's ip@port syntax.
		ipStr, portStr := s, ""
		if strings.Contains(s, "@") {
			parts := strings.SplitN(s, "@", 2)
			ipStr, portStr = parts[0], parts[1]
		} else if ap, err := netip.ParseAddrPort(s); err == nil {
			ipStr = ap.Addr().String()
			portStr = fmt.Sprintf("%d", ap.Port())
		}
		addr, err := netip.ParseAddr(ipStr)
		if err != nil {
			continue
		}
		formatted := addr.String()
		if portStr != "" {
			formatted = fmt.Sprintf("%s@%s", addr.String(), portStr)
		}
		if _, ok := seen[formatted]; !ok {
			seen[formatted] = struct{}{}
			out = append(out, formatted)
		}
	}
	return out
}
