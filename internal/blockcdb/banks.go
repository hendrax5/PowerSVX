package blockcdb

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/powersvx/powersvx/internal/allowlist"
)

// WriteBanksWhitelist writes official bank apexes for dnsdist SuffixMatchNode.
// Also writes banks.lua so dnsdist can dofile() without regenerating the full conf.
func WriteBanksWhitelist(dataDir string) (int, error) {
	dir := Dir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	path := filepath.Join(dir, "banks.whitelist")
	luaPath := filepath.Join(dir, "banks.lua")
	var b strings.Builder
	var lua strings.Builder
	lua.WriteString("-- AUTO-GENERATED by PowerSVX WriteBanksWhitelist\n")
	lua.WriteString("whitelistSMN = newSuffixMatchNode()\n")
	n := 0
	for _, apex := range allowlist.OfficialBankApexes() {
		apex = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(apex), "."))
		if apex == "" {
			continue
		}
		b.WriteString(apex)
		b.WriteByte('\n')
		lua.WriteString("whitelistSMN:add(newDNSName(\"")
		lua.WriteString(apex)
		lua.WriteString(".\"))\n")
		n++
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return 0, err
	}
	if err := os.Rename(tmp, path); err != nil {
		return 0, err
	}
	tmpLua := luaPath + ".tmp"
	if err := os.WriteFile(tmpLua, []byte(lua.String()), 0o644); err != nil {
		return n, err
	}
	return n, os.Rename(tmpLua, luaPath)
}

// FilterBlockNames drops official banks and wildcard owners for CDB keys.
func FilterBlockNames(names []string) []string {
	out := make([]string, 0, len(names))
	for _, name := range names {
		if name, ok := filterBlockName(name); ok {
			out = append(out, name)
		}
	}
	return out
}

// filterBlockName is FilterBlockNames for one name; ok is false when the name is dropped.
func filterBlockName(name string) (string, bool) {
	name = strings.ToLower(strings.TrimSpace(name))
	name = strings.TrimPrefix(name, "*.")
	name = strings.TrimSuffix(name, ".")
	if name == "" || name == "localhost" {
		return "", false
	}
	if allowlist.OfficialBankName(name) {
		return "", false
	}
	return name, true
}
