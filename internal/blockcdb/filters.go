package blockcdb

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/powersvx/powersvx/internal/allowlist"
)

const (
	WhitelistFile      = "whitelist.txt"
	WhitelistCDBFile   = "whitelist.cdb"
	CustomBlackFile    = "custom_blacklist.txt"
	CustomBlackCDBFile = "custom_blacklist.cdb"
	AuthZonesFile      = "authzones.txt"
	AuthZonesCDBFile   = "authzones.cdb"
)

func normalizeDomainSlice(in []string) []string {
	seen := make(map[string]struct{}, len(in))
	out := make([]string, 0, len(in))
	for _, raw := range in {
		d := strings.ToLower(strings.TrimSuffix(strings.TrimSpace(raw), "."))
		d = strings.TrimPrefix(d, "*.")
		if d == "" || d == "localhost" {
			continue
		}
		if _, ok := seen[d]; ok {
			continue
		}
		seen[d] = struct{}{}
		out = append(out, d)
	}
	sort.Strings(out)
	return out
}

// SyncWhitelist writes merged official banks + custom whitelist to whitelist.txt,
// whitelist.cdb, and legacy banks.lua for instant dnsdist KVS evaluation.
func SyncWhitelist(dataDir string, custom []string) (int, error) {
	dir := Dir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	banks := allowlist.OfficialBankApexes()
	merged := make([]string, 0, len(banks)+len(custom))
	merged = append(merged, banks...)
	merged = append(merged, custom...)
	clean := normalizeDomainSlice(merged)

	if _, err := WriteDomainsTxt(filepath.Join(dir, WhitelistFile), clean); err != nil {
		return 0, fmt.Errorf("whitelist.txt: %w", err)
	}
	n, err := BuildCDB(filepath.Join(dir, WhitelistCDBFile), clean)
	if err != nil {
		return 0, fmt.Errorf("whitelist.cdb: %w", err)
	}

	// Keep banks.lua updated for backward-compat deployments still loading dofile("banks.lua").
	var lua strings.Builder
	lua.WriteString("-- AUTO-GENERATED by PowerSVX SyncWhitelist\n")
	lua.WriteString("whitelistSMN = newSuffixMatchNode()\n")
	for _, apex := range clean {
		lua.WriteString("whitelistSMN:add(newDNSName(\"")
		lua.WriteString(apex)
		lua.WriteString(".\"))\n")
	}
	luaPath := filepath.Join(dir, "banks.lua")
	tmpLua := luaPath + ".tmp"
	if err := os.WriteFile(tmpLua, []byte(lua.String()), 0o644); err == nil {
		_ = os.Rename(tmpLua, luaPath)
	}
	return n, nil
}

// SyncCustomBlacklist writes custom operator/admin blocked domains to custom_blacklist.txt + .cdb.
func SyncCustomBlacklist(dataDir string, domains []string) (int, error) {
	dir := Dir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	clean := normalizeDomainSlice(domains)
	if _, err := WriteDomainsTxt(filepath.Join(dir, CustomBlackFile), clean); err != nil {
		return 0, fmt.Errorf("custom_blacklist.txt: %w", err)
	}
	n, err := BuildCDB(filepath.Join(dir, CustomBlackCDBFile), clean)
	if err != nil {
		return 0, fmt.Errorf("custom_blacklist.cdb: %w", err)
	}
	return n, nil
}

// SyncAuthZones writes PowerSVX authoritative zones to authzones.txt + authzones.cdb
// so dnsdist can route hosted authoritative domains directly to the PowerSVX Auth pool (:5354).
