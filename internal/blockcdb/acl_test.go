package blockcdb

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

func TestDNSDistACLMasksEmptyAllowIsOpen(t *testing.T) {
	got := DNSDistACLMasks(nil, nil)
	want := []string{"127.0.0.0/8", "::1/128", "0.0.0.0/0", "::/0"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v want %v", got, want)
	}
}

func TestDNSDistACLMasksAllowDeny(t *testing.T) {
	got := DNSDistACLMasks(
		[]string{"10.0.0.0/8", "103.10.20.5", " ", "bogus", "10.1.2.0/24", "2001:db8::/32"},
		[]string{"10.1.0.0/16", "192.0.2.9"},
	)
	want := []string{
		"127.0.0.0/8", "::1/128",
		"10.0.0.0/8", "103.10.20.5/32", "2001:db8::/32",
		"!10.1.0.0/16", "!192.0.2.9/32",
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v want %v", got, want)
	}
}

func TestWriteDNSDistACL(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("POWERSVX_BLOCKLIST_DIR", "")
	n, err := WriteDNSDistACL(dir, []string{"10.0.0.0/8"}, nil)
	if err != nil || n != 3 {
		t.Fatalf("n=%d err=%v", n, err)
	}
	b, err := os.ReadFile(filepath.Join(Dir(dir), ACLFile))
	if err != nil {
		t.Fatal(err)
	}
	want := "# AUTO-GENERATED by PowerSVX (allow_query/deny_query) - do not hand-edit\n127.0.0.0/8\n::1/128\n10.0.0.0/8\n"
	if string(b) != want {
		t.Fatalf("got %q", b)
	}
}
