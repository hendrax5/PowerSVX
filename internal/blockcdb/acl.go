package blockcdb

import (
	"net/netip"
	"os"
	"path/filepath"
	"strings"
)

// ACLFile is reloaded by dnsdist maintenance() and applied via setACL.
const ACLFile = "acl.txt"

// DNSDistACLMasks converts PowerSVX allow/deny CIDRs to dnsdist NetmaskGroup entries.
// Empty allow = allow all. Deny entries are negated ("!cidr"); allow prefixes that sit
// inside a deny are dropped so deny always wins under dnsdist longest-prefix matching.
func DNSDistACLMasks(allow, deny []string) []string {
	denyP := parsePrefixes(deny)
	allowP := parsePrefixes(allow)
	if len(allowP) == 0 {
		allowP = []netip.Prefix{netip.MustParsePrefix("0.0.0.0/0"), netip.MustParsePrefix("::/0")}
	}
	out := []string{"127.0.0.0/8", "::1/128"}
	seen := map[string]bool{"127.0.0.0/8": true, "::1/128": true}
	for _, p := range allowP {
		if coveredBy(p, denyP) {
			continue
		}
		if s := p.String(); !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	for _, p := range denyP {
		if s := "!" + p.String(); !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

// WriteDNSDistACL writes acl.txt (one mask per line) into the blocklist dir.
func WriteDNSDistACL(dataDir string, allow, deny []string) (int, error) {
	dir := Dir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return 0, err
	}
	masks := DNSDistACLMasks(allow, deny)
	body := "# AUTO-GENERATED by PowerSVX (allow_query/deny_query) - do not hand-edit\n" +
		strings.Join(masks, "\n") + "\n"
	path := filepath.Join(dir, ACLFile)
	if cur, err := os.ReadFile(path); err == nil && string(cur) == body {
		return len(masks), nil
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(body), 0o644); err != nil {
		return 0, err
	}
	return len(masks), os.Rename(tmp, path)
}

func parsePrefixes(in []string) []netip.Prefix {
	out := make([]netip.Prefix, 0, len(in))
	for _, s := range in {
		s = strings.TrimSpace(s)
		if s == "" {
			continue
		}
		if !strings.Contains(s, "/") {
			a, err := netip.ParseAddr(s)
			if err != nil {
				continue
			}
			out = append(out, netip.PrefixFrom(a.Unmap(), a.Unmap().BitLen()))
			continue
		}
		p, err := netip.ParsePrefix(s)
		if err != nil {
			continue
		}
		out = append(out, p.Masked())
	}
	return out
}

func coveredBy(p netip.Prefix, parents []netip.Prefix) bool {
	for _, d := range parents {
		if d.Addr().Is4() == p.Addr().Is4() && d.Bits() <= p.Bits() && d.Contains(p.Addr()) {
			return true
		}
	}
	return false
}
